@dataclass
class Check:
    cid: str
    name: str
    status: str = "SKIP"  # PASS | FAIL | WARN | SKIP
    evidence: str = ""
    duration_s: float = 0.0


@dataclass
class Report:
    checks: list[Check] = field(default_factory=list)
    started_at: str = ""
    finished_at: str = ""
    git_sha: str = ""
    mode: str = "local"

    def add(self, cid: str, name: str, status: str, evidence: str, t0: float) -> None:
        c = Check(cid, name, status, evidence, round(time.monotonic() - t0, 1))
        self.checks.append(c)
        print(f"[{status:4}] {cid} {name}: {evidence}")

    @property
    def fails(self) -> int:
        return sum(1 for c in self.checks if c.status == "FAIL")

    @property
    def verdict(self) -> str:
        return "GO" if self.fails == 0 else "NO-GO"

    def render_md(self) -> str:
        rows = ["| Check | Result | Evidence |", "|---|---|---|"]
        for c in self.checks:
            rows.append(f"| {c.name} | {c.status} | {c.evidence.replace('|', '/')} |")
        warns = [c for c in self.checks if c.status == "WARN"]
        lines = [
            f"# Pilot release-readiness report — {self.verdict}",
            "",
            f"- Mode: `{self.mode}` · Commit: `{self.git_sha}`",
            f"- Started: {self.started_at} · Finished: {self.finished_at}",
            f"- {len(self.checks)} checks: {self.fails} FAIL, {len(warns)} WARN, "
            f"{sum(1 for c in self.checks if c.status == 'PASS')} PASS, "
            f"{sum(1 for c in self.checks if c.status == 'SKIP')} SKIP",
            "",
            *rows,
            "",
        ]
        if warns:
            lines += ["## Warnings", ""]
            lines += [f"- **{c.name}** — {c.evidence}" for c in warns]
            lines += [""]
        if self.fails:
            lines += ["## Blocking failures", ""]
            lines += [f"- **{c.name}** — {c.evidence}" for c in self.checks if c.status == "FAIL"]
            lines += [""]
        lines += [
            "## Method",
            "",
            "Generated by `deploy/release_readiness.py` against a real stack: embedded",
            "PostgreSQL + Alembic migrations + API/worker subprocesses under",
            "`APP_ENV=staging` configuration. Model calls are not exercised (pilot",
            "readiness of deployment plumbing, not of agent quality).",
        ]
        return "\n".join(lines)

    def write(self, out_dir: Path) -> tuple[Path, Path]:
        out_dir.mkdir(parents=True, exist_ok=True)
        stamp = self.finished_at.replace(":", "").replace("-", "").split(".")[0]
        j = out_dir / f"release-readiness-{stamp}.json"
        m = out_dir / f"release-readiness-{stamp}.md"
        j.write_text(
            json.dumps(
                {
                    "verdict": self.verdict,
                    "mode": self.mode,
                    "git_sha": self.git_sha,
                    "started_at": self.started_at,
                    "finished_at": self.finished_at,
                    "checks": [c.__dict__ for c in self.checks],
                },
                indent=2,
            )
        )
        m.write_text(self.render_md())
        return j, m


