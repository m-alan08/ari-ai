def _scratch_db(tmp: Path) -> tuple[str, str]:
    """Start embedded Postgres, create a scratch database, return its URL."""
    from backend.devdb import start

    admin_url = start(tmp / "pgdata", database="postgres")
    name = f"readiness_{int(time.time())}"
    import sqlalchemy as sa

    engine = sa.create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with engine.connect() as c:
        c.execute(sa.text(f'CREATE DATABASE "{name}"'))
    url = sa.engine.make_url(admin_url).set(database=name).render_as_string(hide_password=False)
    return admin_url, url


def _pg_bin() -> str | None:
    try:
        import pgserver

        d = Path(pgserver.__file__).resolve().parent / "pginstall" / "bin"
        return str(d) if (d / "pg_dump").exists() else None
    except Exception:
        return None


def _rl_env(report: Report, t0: float) -> dict[str, str]:
    ck = REPO / "rl-defense/results/protocol-v1-retrain/checkpoints/ddqn_seed0.pt"
    topo = REPO / "rl-defense/configs/topology/payments_lite.yaml"
    if not ck.exists():
        cands = sorted(REPO.glob("rl-defense/results/**/*.pt"))
        ck = cands[0] if cands else ck
    env: dict[str, str] = {}
    if ck.exists() and topo.exists():
        env["RL_CHECKPOINT_PATH"] = str(ck)
        env["RL_CHECKPOINT_SHA256"] = hashlib.sha256(ck.read_bytes()).hexdigest()
        env["RL_TOPOLOGY_PATH"] = str(topo)
    return env


