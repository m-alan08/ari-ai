def _port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def http(
    url: str,
    *,
    method: str = "GET",
    headers: dict[str, str] | None = None,
    body: Any = None,
    timeout: float = 10,
) -> tuple[int, dict | list | str]:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers=headers or {})
    if data:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            raw = r.read()
            code = r.status
    except urllib.error.HTTPError as e:
        raw, code = e.read(), e.code
    except Exception as e:
        return -1, f"{type(e).__name__}: {e}"
    try:
        return code, json.loads(raw)
    except Exception:
        return code, raw.decode(errors="replace")[:500]


def wait_http(url: str, timeout: float = 60) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        code, _ = http(url, timeout=2)
        if code == 200:
            return True
        time.sleep(0.3)
    return False


def wait_db(predicate, timeout: float = 60, interval: float = 0.5) -> Any:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        value = predicate()
        if value:
            return value
        time.sleep(interval)
    return None


def sh(
    args: list[str],
    *,
    env: dict[str, str] | None = None,
    timeout: float = 300,
    cwd: Path = REPO,
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, capture_output=True, text=True, timeout=timeout, cwd=cwd, env=env)


class AlertSink:
    """Local webhook sink: records every POST so alerting can be verified."""

    def __init__(self) -> None:
        self.bodies: list[dict] = []
        sink = self

        class H(BaseHTTPRequestHandler):
            def do_POST(self) -> None:  # noqa: N802
                data = self.rfile.read(int(self.headers.get("Content-Length", 0)))
                try:
                    sink.bodies.append(json.loads(data))
                except Exception:
                    sink.bodies.append({"_raw": data.decode(errors="replace")})
                self.send_response(200)
                self.end_headers()

            def log_message(self, *_: Any) -> None:
                pass

        self.server = HTTPServer(("127.0.0.1", 0), H)
        self.port = self.server.server_address[1]
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def wait_for(self, event: str, timeout: float = 30) -> dict | None:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            for b in self.bodies:
                if b.get("event") == event:
                    return b
            time.sleep(0.3)
        return None

    def close(self) -> None:
        self.server.shutdown()


class Proc:
    """A managed subprocess with its stderr captured to a file."""

    def __init__(self, args: list[str], env: dict[str, str], log: Path) -> None:
        self.log = log
        self._fh = open(log, "wb")
        self.p = subprocess.Popen(args, env=env, stdout=self._fh, stderr=subprocess.STDOUT)

    @property
    def pid(self) -> int:
        return self.p.pid

    def alive(self) -> bool:
        return self.p.poll() is None

    def term(self) -> int | None:
        if self.alive():
            self.p.terminate()
        try:
            return self.p.wait(timeout=20)
        except subprocess.TimeoutExpired:
            self.p.kill()
            return self.p.wait(timeout=10)

    def kill(self) -> None:
        if self.alive():
            self.p.send_signal(signal.SIGKILL)

    def close(self) -> None:
        self._fh.close()

    def text(self) -> str:
        self._fh.flush()
        return self.log.read_text(errors="replace")


