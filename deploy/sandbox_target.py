"""Sandbox target for Ari's security agents: build_recipe.json names
`deploy.sandbox_target:create_app`. Generated by Ari; never imported by the app itself.

Starts a throwaway local PostgreSQL over a Unix socket, applies the app's own Alembic
migrations, seeds two unrelated users (alice, bob) who each own one project, and maps
the two fixed Authorization headers onto those users' session cookies.
Synthetic values only; no network calls.
"""

from __future__ import annotations

import glob
import hashlib
import os
import subprocess
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
for _path in (REPO_ROOT / "backend", REPO_ROOT / "shared"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

PG_SOCKET_DIR = "/tmp/hackatl_sandbox_pg"
PG_DATA_DIR = "/tmp/hackatl_sandbox_pgdata"
PG_DB = "hackatl_sandbox"
SESSION_COOKIE = "hackatl_session"

FIXTURE_USERS = {
    "alice": {
        "authorization": "Bearer sbx-alice-session-0001",
        "session": "sbx-alice-session-0001",
        "user_id": "usr_sbx_alice",
        "org_id": "org_sbx_alice",
        "project_id": "prj_sbx_alice_0001",
    },
    "bob": {
        "authorization": "Bearer sbx-bob-session-0001",
        "session": "sbx-bob-session-0001",
        "user_id": "usr_sbx_bob",
        "org_id": "org_sbx_bob",
        "project_id": "prj_sbx_bob_0001",
    },
}
_SESSION_BY_AUTH = {u["authorization"]: u["session"] for u in FIXTURE_USERS.values()}
_APP = None


def _pg_binary(name: str) -> str:
    hits = sorted(glob.glob(f"/usr/lib/postgresql/*/bin/{name}"))
    if not hits:
        raise RuntimeError(f"{name} not found: install the apt package 'postgresql'")
    return hits[-1]


def _as_postgres(*argv: str) -> None:
    subprocess.run(
        ["runuser", "-u", "postgres", "--", *argv], check=True, capture_output=True, text=True
    )


def _ensure_postgres() -> None:
    os.makedirs(PG_SOCKET_DIR, exist_ok=True)
    subprocess.run(["chown", "postgres:postgres", PG_SOCKET_DIR], check=True)
    log_file = os.path.join(PG_SOCKET_DIR, "server.log")
    if not os.path.exists(os.path.join(PG_DATA_DIR, "PG_VERSION")):
        os.makedirs(PG_DATA_DIR, exist_ok=True)
        subprocess.run(["chown", "postgres:postgres", PG_DATA_DIR], check=True)
        _as_postgres(
            _pg_binary("initdb"), "-D", PG_DATA_DIR, "-U", "postgres", "--auth=trust", "-E", "UTF8"
        )
    try:
        _as_postgres(_pg_binary("pg_ctl"), "-D", PG_DATA_DIR, "status")
    except subprocess.CalledProcessError:
        _as_postgres(
            _pg_binary("pg_ctl"),
            "-D",
            PG_DATA_DIR,
            "-o",
            f"-k {PG_SOCKET_DIR} -c listen_addresses=",
            "-l",
            log_file,
            "-w",
            "start",
        )


def _ensure_database() -> str:
    import psycopg

    with psycopg.connect(
        f"host={PG_SOCKET_DIR} dbname=postgres user=postgres", autocommit=True
    ) as conn:
        if conn.execute("SELECT 1 FROM pg_database WHERE datname = %s", (PG_DB,)).fetchone() is None:
            conn.execute(f'CREATE DATABASE "{PG_DB}"')
    return f"postgresql+psycopg://postgres@/{PG_DB}?host={PG_SOCKET_DIR}"


def _seed(database_url: str) -> None:
    import sqlalchemy as sa

    from backend.db import memberships, organizations, projects, sessions, users
    from shared.tenancy import ProjectSettings

    engine = sa.create_engine(database_url)
    now = datetime.now(UTC)
    with engine.begin() as conn:
        for table in (sessions, projects, memberships, users, organizations):
            conn.execute(sa.delete(table))
        for name, fx in FIXTURE_USERS.items():
            conn.execute(
                sa.insert(organizations).values(id=fx["org_id"], name=f"{name} (personal)")
            )
            conn.execute(
                sa.insert(users).values(
                    id=fx["user_id"],
                    github_login=name,
                    display_name=name.title(),
                    personal_org_id=fx["org_id"],
                )
            )
            conn.execute(
                sa.insert(memberships).values(
                    org_id=fx["org_id"], user_id=fx["user_id"], role="owner"
                )
            )
            conn.execute(
                sa.insert(projects).values(
                    id=fx["project_id"],
                    org_id=fx["org_id"],
                    name=f"{name}-sandbox",
                    settings=ProjectSettings().model_dump(mode="json"),
                )
            )
            conn.execute(
                sa.insert(sessions).values(
                    token_hash=hashlib.sha256(fx["session"].encode()).hexdigest(),
                    user_id=fx["user_id"],
                    csrf_token=hashlib.sha256(("csrf-" + fx["session"]).encode()).hexdigest(),
                    expires_at=now + timedelta(days=1),
                )
            )
    engine.dispose()


class _SandboxAuthBridge:
    """Pure ASGI: maps each fixed Authorization header to that user's session cookie."""

    def __init__(self, app):  # type: ignore[no-untyped-def]
        self.app = app

    async def __call__(self, scope, receive, send):  # type: ignore[no-untyped-def]
        if scope["type"] in ("http", "websocket"):
            headers = list(scope.get("headers") or [])
            auth = next((v.decode("latin-1") for k, v in headers if k == b"authorization"), None)
            session = _SESSION_BY_AUTH.get(auth) if auth else None
            if session is not None:
                headers = [(k, v) for k, v in headers if k != b"cookie"]
                headers.append((b"cookie", f"{SESSION_COOKIE}={session}".encode("latin-1")))
                scope = {**scope, "headers": headers}
        await self.app(scope, receive, send)


def create_app():  # type: ignore[no-untyped-def]
    global _APP
    if _APP is None:
        _ensure_postgres()
        database_url = _ensure_database()
        os.environ.update(
            {
                "APP_ENV": "test",
                "DATABASE_URL": database_url,
                "ARTIFACT_STORE_URI": "file:///tmp/hackatl_sandbox_artifacts",
                "AUTH_DEV_LOGIN_ENABLED": "false",
            }
        )
        from backend.settings import get_settings

        get_settings.cache_clear()
        from backend.migrate import upgrade

        upgrade()
        _seed(database_url)

        from backend.main import create_app as build_app

        app = build_app()
        app.add_middleware(_SandboxAuthBridge)
        _APP = app
    return _APP
