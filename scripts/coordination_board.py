#!/usr/bin/env python3
"""Regenerate coordination/AGENT_BOARD.md from structured status records + GitHub PRs.

Source of truth order: GitHub > structured records. The board is a *rendered view* —
agents update their own `coordination/status/agents/<agent>.json` (one file each, no
shared-file write contention) and this script compiles the dashboard.

Usage:
    python3 scripts/coordination_board.py [--check] [--out coordination/AGENT_BOARD.md]

    --check  exit 1 if the committed board is stale (used by CI)
    --out    write path (default coordination/AGENT_BOARD.md)

PR data comes from `gh pr list` when available, or the REST API via $GH_TOKEN /
$GITHUB_TOKEN. When neither is reachable the board renders PR columns as "?" instead of
failing — a stale-but-readable board beats a hard error.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS_DIR = ROOT / "coordination" / "status" / "agents"
BOARD_PATH = ROOT / "coordination" / "AGENT_BOARD.md"
COMMS_ISSUE = 559
REPO = "adamissac/ari-ai"

STATES = [
    "CLAIMED",
    "WORKING",
    "NEEDS_COORDINATION",
    "BLOCKED",
    "READY_FOR_REVIEW",
    "MERGED",
    "DONE",
]


def load_agents() -> list[dict]:
    agents = []
    if not AGENTS_DIR.is_dir():
        return agents
    for path in sorted(AGENTS_DIR.glob("*.json")):
        try:
            rec = json.loads(path.read_text())
        except json.JSONDecodeError as exc:
            print(f"warning: {path.name} is not valid JSON: {exc}", file=sys.stderr)
            continue
        rec["_file"] = path.name
        agents.append(rec)
    return agents


def fetch_prs() -> dict[int, dict]:
    """Open PRs keyed by number: {title, branch, sha, mergeable}."""
    out: dict[int, dict] = {}
    try:
        r = subprocess.run(
            [
                "gh",
                "pr",
                "list",
                "--repo",
                REPO,
                "--state",
                "open",
                "--limit",
                "100",
                "--json",
                "number,title,headRefName,headRefOid,author",
            ],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if r.returncode == 0:
            for p in json.loads(r.stdout):
                out[p["number"]] = {
                    "title": p["title"],
                    "branch": p["headRefName"],
                    "sha": (p.get("headRefOid") or "")[:8],
                    "author": (p.get("author") or {}).get("login", "?"),
                }
            return out
    except (FileNotFoundError, subprocess.TimeoutExpired):
        pass
    token = None
    for var in ("GH_TOKEN", "GITHUB_TOKEN"):
        token = token or __import__("os").environ.get(var)
    if not token:
        return out
    try:
        req = urllib.request.Request(
            f"https://api.github.com/repos/{REPO}/pulls?state=open&per_page=100",
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
            },
        )
        for p in json.load(urllib.request.urlopen(req, timeout=30)):
            out[p["number"]] = {
                "title": p["title"],
                "branch": p["head"]["ref"],
                "sha": p["head"]["sha"][:8],
                "author": (p.get("user") or {}).get("login", "?"),
            }
    except Exception as exc:  # noqa: BLE001 — board must still render
        print(f"warning: PR fetch failed ({exc}); PR column rendered as '?'", file=sys.stderr)
    return out


def row(*cols: str) -> str:
    return "| " + " | ".join(c.replace("\n", " ") for c in cols) + " |"


def render(agents: list[dict], prs: dict[int, dict]) -> str:
    now = datetime.now(timezone.utc).strftime  # noqa: UP017 — script must run on py<3.11 too("%Y-%m-%d %H:%M UTC")
    lines = [
        "<!-- GENERATED by scripts/coordination_board.py — do not hand-edit. -->",
        "<!-- Update your own coordination/status/agents/<agent>.json and re-render. -->",
        "",
        "# Agent board — live coordination dashboard",
        "",
        f"Regenerated {now}. Comms channel: [issue #{COMMS_ISSUE}]"
        f"(https://github.com/{REPO}/issues/{COMMS_ISSUE}). Protocol: `coordination/PROTOCOL.md`.",
        "",
        "## Active agents",
        "",
        row("Agent", "Owner", "Workstream", "State", "Task", "Branch", "SHA"),
        row("---", "---", "---", "---", "---", "---", "---"),
    ]
    for a in agents:
        lines.append(
            row(
                str(a.get("agent", "?")),
                str(a.get("human_owner", "?")),
                str(a.get("workstream", "?")),
                str(a.get("state", "?")),
                str(a.get("task", "?")),
                str(a.get("branch", "?")),
                str(a.get("latest_sha", "?")),
            )
        )

    lines += ["", "## PR ownership and merge order", ""]
    lines += [
        row("PR", "Title", "Branch", "Head", "Owned by", "Merge position"),
        row("---", "---", "---", "---", "---", "---"),
    ]
    # merge position = order of appearance across agents' prs lists, else "—"
    order: dict[int, int] = {}
    pos = 0
    for a in agents:
        for n in a.get("prs", []):
            if n not in order:
                order[n] = pos
                pos += 1
    owner_of: dict[int, str] = {}
    for a in agents:
        for n in a.get("prs", []):
            owner_of.setdefault(n, str(a.get("agent", "?")))
    for n in sorted(order):
        p = prs.get(n, {})
        lines.append(
            row(
                f"#{n}",
                str(p.get("title", "?")),
                str(p.get("branch", "?")),
                str(p.get("sha", "?")),
                owner_of.get(n, "?"),
                str(order[n]),
            )
        )
    for n, p in sorted(prs.items()):
        if n not in order:
            lines.append(
                row(f"#{n}", str(p["title"]), str(p["branch"]), str(p["sha"]), "unassigned", "—")
            )

    lines += ["", "## File / subsystem claims", ""]
    for a in agents:
        claims = a.get("claims", [])
        if claims:
            lines.append(f"- **{a.get('agent', '?')}**: " + ", ".join(f"`{c}`" for c in claims))

    lines += ["", "## Dependencies", ""]
    for a in agents:
        for d in a.get("depends_on", []):
            lines.append(f"- **{a.get('agent', '?')}** depends on {d}")

    lines += ["", "## Blockers", ""]
    any_blocker = False
    for a in agents:
        for b in a.get("blockers", []):
            any_blocker = True
            lines.append(f"- **{a.get('agent', '?')}**: {b}")
    if not any_blocker:
        lines.append("- none recorded")

    lines += ["", "## Next actions", ""]
    for a in agents:
        if a.get("next_action"):
            lines.append(f"- **{a.get('agent', '?')}**: {a['next_action']}")

    lines += [
        "",
        "## How to update",
        "",
        "1. Edit **only your own** `coordination/status/agents/<agent>.json`.",
        "2. Run `python3 scripts/coordination_board.py` and commit the regenerated board",
        "   in the same small commit.",
        "3. Post live messages as comments on issue "
        f"[#{COMMS_ISSUE}](https://github.com/{REPO}/issues/{COMMS_ISSUE}) — not by editing",
        "   this file or anyone else's status record.",
        "",
        "States: `CLAIMED → WORKING → READY_FOR_REVIEW → MERGED → DONE`, with",
        "`NEEDS_COORDINATION` and `BLOCKED` usable at any point.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed board is stale")
    ap.add_argument("--out", type=Path, default=BOARD_PATH)
    args = ap.parse_args()

    rendered = render(load_agents(), fetch_prs())
    if args.check:
        if not args.out.is_file() or args.out.read_text() != rendered:
            print(
                f"{args.out} is stale — run `python3 scripts/coordination_board.py`",
                file=sys.stderr,
            )
            return 1
        print("board is fresh")
        return 0
    args.out.write_text(rendered)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
